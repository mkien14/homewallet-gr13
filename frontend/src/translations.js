export function t(text, locale = globalThis.localStorage?.getItem("hw.locale") || "vi") {
  const normalizedText = text.replace(/&nbsp;/gu, " ");
  if (locale !== "en") return normalizedText;
  const leading = text.match(/^\s*/u)?.[0] || "";
  const trailing = text.match(/\s*$/u)?.[0] || "";
  const key = normalizedText.trim().replace(/\s+/gu, " ");
  let translated = Object.hasOwn(messages.en, key) ? messages.en[key] : null;
  if (translated === null) {
    for (const [pattern, render] of validationPatterns) {
      const match = key.match(pattern);
      if (match) { translated = render(...match.slice(1)); break; }
    }
  }
  return `${leading}${translated ?? key}${trailing}`;
}
